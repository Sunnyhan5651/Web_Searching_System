def main() -> None:
    data = json.loads(MASTER.read_text(encoding="utf-8"))
    changed = 0
    for c in data["cases"]:
        u = UPDATES.get(c["id"])
        if not u:
            continue
        key = c["id"].split("-")[0]
        before = {k: c.get(k) for k in ("title", "summary", "disposition")}
        for k, v in u.items():
            if k == "note":
                continue
            c[k] = v
        if key == "sdm":
            c["target_org"] = "서대문구 치수과"
        c["source_document"] = SOURCE_DOCS[key]
        c["verified_at"] = VERIFIED_AT
        c["review_status"] = "source_checked"
        notes = [f"{VERIFIED_AT} 원문 PDF 대조"]
        if before["disposition"] != c.get("disposition"):
            notes.append(f"처분 {before['disposition']} → {c['disposition']}")
        if before["summary"] != c.get("summary") and "summary" in u:
            notes.append("요약을 원문 기준으로 작성·갱신")
        if before["title"] != c.get("title"):
            notes.append("제목 정정")
        if u.get("note"):
            notes.append(u["note"])
        notes.append("감사실 승인 전")
        c["review_note"] = " / ".join(dict.fromkeys(notes))
        changed += 1
    MASTER.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"[완료] {changed}건 반영")


if __name__ == "__main__":
    main()
